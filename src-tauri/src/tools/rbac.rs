pub fn ensure_permission(role: UserRole, tool_name: &str) -> Result<(), String> {
    let is_allowed = match role {
        UserRole::Owner => true,
        UserRole::PowerUser => {
            POWER_USER_TOOLS.contains(&tool_name) || VIEWER_TOOLS.contains(&tool_name)
        }
        UserRole::Viewer => VIEWER_TOOLS.contains(&tool_name),
    };

    if is_allowed {
        Ok(())
    } else {
        Err(format!(
            "ACCESO DENEGADO: El rol '{:?}' no tiene permisos para ejecutar la herramienta '{}'.",
            role, tool_name
        ))
    }
}

pub fn is_owner_only_tool(tool_name: &str) -> bool {
    !VIEWER_TOOLS.contains(&tool_name) && !POWER_USER_TOOLS.contains(&tool_name)
}
